          <p>Buying your first home is exciting — and overwhelming. Between mortgage pre-approvals, inspections, and negotiations, it's easy to feel lost. Here's a practical checklist to help you move through the process with confidence.</p>

          <h2>1. Know your real budget</h2>
          <p>Get pre-approved before you start touring homes. A pre-approval tells you exactly what you can afford and signals to sellers that you're a serious buyer.</p>

          <h2>2. Don't skip the inspection</h2>
          <p>A home inspection can reveal costly issues hiding behind fresh paint — foundation cracks, outdated wiring, or roof damage. It's a small cost that can save you thousands.</p>

          <blockquote>"The biggest mistake first-time buyers make is falling in love with a house before checking the numbers." — Sarah Mitchell, Head of Sales</blockquote>

          <h2>3. Factor in closing costs</h2>
          <p>Closing costs typically run 2–5% of the purchase price. Budget for these on top of your down payment so there are no surprises at signing.</p>

          <ul>
            <li>Get pre-approved, not just pre-qualified</li>
            <li>Always schedule a professional inspection</li>
            <li>Budget for closing costs and moving expenses</li>
            <li>Research the neighborhood at different times of day</li>
            <li>Work with an agent who represents your interests</li>
          </ul>

          <h2>4. Think beyond the listing photos</h2>
          <p>Visit at different times of day, check commute times, and talk to a few neighbors if you can. The listing photos only tell part of the story.</p>

          <p>Buying a home is a big step, but it doesn't have to be a stressful one. With the right preparation — and the right agent — you can walk into closing day with confidence instead of anxiety.</p>
